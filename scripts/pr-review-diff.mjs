#!/usr/bin/env node
/**
 * Scopes a PR diff down to the files worth a human-grade review, and prints it with the
 * line numbers the GitHub review API needs.
 *
 * Two jobs, and the first one is the reason this is a script rather than an instruction in
 * the review prompt:
 *
 *   1. Exclusions are mechanical. Tests, e2e, the generated proxy, Markdown and generated
 *      artefacts are never reviewed here. An instruction to skip them is an instruction that
 *      can be forgotten after the diff is already in context, by which point the context is
 *      already spent. Filtering before the agent ever sees the patch is the only version of
 *      that rule that actually holds.
 *   2. Anchoring. A review comment that floats at the bottom of the PR makes the author go
 *      find the line. GitHub's review API wants a `line` (and `side`) that lands inside a
 *      diff hunk, and gives a bare 422 when it does not. Every emitted line carries its own
 *      `R<n>` / `L<n>` marker, so the reviewer copies an anchor instead of deriving one.
 *   3. Prior art. With `--pr`, it also lists what has already been said on this PR. Copilot
 *      reviews every PR on this repo and humans review on top of it, so a reviewer that does
 *      not read the existing threads first will re-report findings the author has already
 *      answered. That is the fastest way to get a review ignored.
 *
 * Nothing here is silently dropped: every exclusion is counted and reported by category, and
 * a truncated diff says how much it left out.
 *
 * Usage:
 *   node scripts/pr-review-diff.mjs                    # working branch vs origin/dev
 *   node scripts/pr-review-diff.mjs --base origin/uat
 *   node scripts/pr-review-diff.mjs --pr 57            # an open PR, via gh
 *   node scripts/pr-review-diff.mjs --files-only       # scope report, no patch
 *   node scripts/pr-review-diff.mjs --max-lines 8000
 */

import { execFileSync } from 'node:child_process';

const DEFAULT_BASE = 'origin/dev';
const DEFAULT_MAX_LINES = 4000;

/**
 * Never reviewed. The first four categories are the non-negotiable ones: they are governed by
 * their own standards and their own gates, and reviewing them here buys nothing but context.
 * `generated` is the same argument applied to files no human wrote.
 */
const EXCLUSIONS = [
  {
    category: 'tests',
    why: 'covered by docs/standards/backend/testing.md and the suite itself',
    match: (f) =>
      /(^|\/)(__tests__|__mocks__|tests?)\//.test(f) ||
      /\.(test|spec)\.[cm]?[jt]sx?$/.test(f) ||
      /(^|\/)[^/]*Tests?\.cs$/.test(f) ||
      /(^|\/)[^/]*\.Tests\//.test(f),
  },
  {
    category: 'e2e',
    why: 'covered by docs/standards/e2e-testing.md and the attestation gate',
    match: (f) => f.startsWith('e2e/') || /(^|\/)maestro\//.test(f),
  },
  {
    category: 'proxy',
    why: 'generated by Orval; review the backend contract instead',
    match: (f) => f.includes('/src/proxy/'),
  },
  {
    category: 'markdown',
    why: 'covered by check:markdown',
    match: (f) => /\.mdx?$/i.test(f),
  },
  {
    category: 'generated',
    why: 'machine-written',
    match: (f) =>
      f === 'package-lock.json' ||
      f.startsWith('graphify-out/') ||
      /\/Migrations\/.*(\.Designer\.cs|ModelSnapshot\.cs)$/.test(f) ||
      // Committed OpenAPI schemas: the output of the backend contract, not the contract.
      // Review the controller and the DTO instead.
      /(^|\/)openapi\/.*\.json$/.test(f) ||
      /(^|\/)(dist|coverage|test-results|playwright-report)\//.test(f),
  },
];

function parseArgs(argv) {
  const args = { base: DEFAULT_BASE, pr: null, filesOnly: false, maxLines: DEFAULT_MAX_LINES };
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    if (flag === '--base') args.base = argv[++i];
    else if (flag === '--pr') args.pr = argv[++i];
    else if (flag === '--files-only') args.filesOnly = true;
    else if (flag === '--max-lines') {
      // Validated, not just coerced: `Number(undefined)` and `Number('abc')` are NaN, and
      // `emitted >= NaN` is always false, which silently turns the cap off and dumps the whole
      // diff. A malformed cap must fail loudly rather than become no cap at all.
      const raw = argv[++i];
      const value = Number(raw);
      if (!Number.isFinite(value) || value <= 0) {
        throw new Error(`--max-lines needs a positive number, got ${JSON.stringify(raw ?? null)}`);
      }
      args.maxLines = value;
    }
    else if (flag === '--help' || flag === '-h') args.help = true;
    else throw new Error(`unknown flag: ${flag}`);
  }
  return args;
}

function capture(command, commandArgs) {
  return execFileSync(command, commandArgs, {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  });
}

function loadPatch({ pr, base }) {
  if (pr) {
    return { patch: capture('gh', ['pr', 'diff', pr, '--patch']), source: `PR #${pr}` };
  }
  // --merge-base so a stale local base branch does not surface unrelated files as "changed".
  const patch = capture('git', ['diff', '--merge-base', base, 'HEAD']);
  return { patch, source: `${base}...HEAD` };
}

/**
 * Everything already said on this PR: line-anchored review comments and the floating issue
 * comments. Best-effort — an unauthenticated `gh` or a network failure must degrade to "no
 * prior art known" rather than killing the scope report, so the caller can still review.
 */
function loadExistingComments(pr) {
  try {
    const repo = capture('gh', ['repo', 'view', '--json', 'nameWithOwner', '-q', '.nameWithOwner'])
      .trim();
    const fetch = (endpoint) =>
      JSON.parse(
        capture('gh', ['api', `repos/${repo}/${endpoint}?per_page=100`, '--paginate', '--slurp'])
          .trim() || '[]',
      ).flat();
    return {
      review: fetch(`pulls/${pr}/comments`),
      issue: fetch(`issues/${pr}/comments`),
      error: null,
    };
  } catch (error) {
    return { review: [], issue: [], error: error.message };
  }
}

/** First sentence or so of a comment, with code fences and reply chrome stripped. */
function gist(body, limit = 160) {
  const flat = String(body ?? '')
    .replace(/```[\s\S]*?```/g, '[code]')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return flat.length > limit ? `${flat.slice(0, limit)}…` : flat;
}

/** Splits a unified patch into one entry per file, keeping the raw hunk lines. */
function splitByFile(patch) {
  const files = [];
  let current = null;
  for (const line of patch.split('\n')) {
    if (line.startsWith('diff --git ')) {
      // `diff --git a/<path> b/<path>` — take the b-side, which is the post-change path.
      const match = / b\/(.+)$/.exec(line);
      current = { path: match ? match[1] : line.slice(11), lines: [], added: 0, removed: 0 };
      files.push(current);
    } else if (current) {
      current.lines.push(line);
      if (line.startsWith('+') && !line.startsWith('+++')) current.added += 1;
      if (line.startsWith('-') && !line.startsWith('---')) current.removed += 1;
    }
  }
  return files;
}

/**
 * Re-emits a file's hunks with per-line anchors. `R<n>` is the new-file line number, usable
 * directly as `line` with `"side": "RIGHT"`; `L<n>` is the old-file number, for `"side": "LEFT"`.
 */
function annotate(file) {
  const out = [];
  let inHunk = false;
  let oldLine = 0;
  let newLine = 0;

  for (const line of file.lines) {
    if (line.startsWith('@@')) {
      const match = /^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(line);
      if (!match) continue;
      oldLine = Number(match[1]);
      newLine = Number(match[2]);
      inHunk = true;
      out.push(line.slice(0, line.indexOf('@@', 2) + 2));
      continue;
    }
    // `inHunk` rather than a truthy `oldLine`: an added file's header is `@@ -0,0 +1,N @@`, so
    // testing `oldLine` skipped every line of every new file and emitted an empty diff block
    // under a correct-looking filename. "Have we passed a hunk header" is its own question.
    if (line.startsWith('+++') || line.startsWith('---') || !inHunk) continue;

    if (line.startsWith('+')) {
      out.push(`+ R${newLine}\t${line.slice(1)}`);
      newLine += 1;
    } else if (line.startsWith('-')) {
      out.push(`- L${oldLine}\t${line.slice(1)}`);
      oldLine += 1;
    } else if (line.startsWith(' ')) {
      out.push(`  R${newLine}\t${line.slice(1)}`);
      oldLine += 1;
      newLine += 1;
    } else if (line.startsWith('\\')) {
      out.push(`  ${line}`);
    }
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    process.stdout.write(
      'node scripts/pr-review-diff.mjs [--base <ref>] [--pr <n>] [--files-only] [--max-lines <n>]\n' +
        `  --base       ref to compare against (default ${DEFAULT_BASE})\n` +
        '  --pr         review an open PR by number, via gh, instead of the local branch\n' +
        '  --files-only scope report without the patch\n' +
        `  --max-lines  cap on emitted diff lines (default ${DEFAULT_MAX_LINES})\n`,
    );
    return;
  }

  const { patch, source } = loadPatch(args);
  const files = splitByFile(patch);

  const reviewable = [];
  const skipped = new Map();
  for (const file of files) {
    const exclusion = EXCLUSIONS.find((rule) => rule.match(file.path));
    if (exclusion) {
      const bucket = skipped.get(exclusion.category) ?? { why: exclusion.why, paths: [] };
      bucket.paths.push(file.path);
      skipped.set(exclusion.category, bucket);
    } else {
      reviewable.push(file);
    }
  }

  const totalAdded = reviewable.reduce((sum, f) => sum + f.added, 0);
  const totalRemoved = reviewable.reduce((sum, f) => sum + f.removed, 0);

  const report = [];
  report.push(`# PR review scope — ${source}`);
  report.push('');
  report.push(
    `reviewable: ${reviewable.length} file(s), +${totalAdded} / -${totalRemoved}` +
      `   |   excluded: ${files.length - reviewable.length} file(s)`,
  );
  report.push('');

  if (skipped.size > 0) {
    report.push('## Excluded (not reviewed, by design)');
    for (const [category, { why, paths }] of skipped) {
      report.push(`- **${category}** (${paths.length}) — ${why}`);
    }
    report.push('');
  }

  if (reviewable.length === 0) {
    report.push(
      files.length === 0
        ? 'No changed files. Check the base ref, or commit the work first.'
        : 'Nothing to review: every changed file falls in an excluded category.',
    );
    process.stdout.write(`${report.join('\n')}\n`);
    return;
  }

  report.push('## Files in scope');
  for (const file of reviewable) {
    report.push(`- \`${file.path}\`  +${file.added} / -${file.removed}`);
  }
  report.push('');

  if (args.pr) {
    const existing = loadExistingComments(args.pr);
    report.push('## Already commented — do not repeat these');
    if (existing.error) {
      report.push(
        `> Could not read the existing threads (\`${existing.error.trim()}\`). Every finding ` +
          'below may already have been raised: check the PR in the browser before posting.',
      );
    } else if (existing.review.length === 0 && existing.issue.length === 0) {
      report.push('No comments on this PR yet.');
    } else {
      report.push(
        `${existing.review.length} line comment(s), ${existing.issue.length} floating comment(s). ` +
          'A finding already raised here is not a finding: skip it. If yours is a materially ' +
          'different claim about the same line, say how it differs in the first clause.',
      );
      report.push('');
      for (const comment of existing.review) {
        const anchor = comment.line ?? comment.original_line ?? '?';
        const thread = comment.in_reply_to_id ? ' (reply)' : '';
        report.push(
          `- \`${comment.path}:${anchor}\` **${comment.user?.login}**${thread}: ${gist(comment.body)}`,
        );
      }
      for (const comment of existing.issue) {
        report.push(`- _(PR-level)_ **${comment.user?.login}**: ${gist(comment.body)}`);
      }
    }
    report.push('');
  }

  if (args.filesOnly) {
    process.stdout.write(`${report.join('\n')}\n`);
    return;
  }

  report.push('## Diff');
  report.push('');
  report.push(
    'Anchors: `R<n>` is the new-file line — use it as `line` with `"side": "RIGHT"`. ' +
      '`L<n>` is the old-file line — `"side": "LEFT"`. Only these numbers are valid anchors; ' +
      'a `line` outside a hunk is rejected with a 422.',
  );
  report.push('');

  let emitted = 0;
  let truncatedAt = null;
  // Recorded on the way out rather than recovered with findIndex afterwards: two entries can
  // share a path (a rename shows the same b-side twice), and the index is what the coverage
  // count depends on.
  let truncatedIndex = -1;
  for (const [index, file] of reviewable.entries()) {
    if (truncatedAt) break;
    const body = annotate(file);
    report.push(`### ${file.path}`);
    report.push('```diff');
    for (const line of body) {
      if (emitted >= args.maxLines) {
        truncatedAt = file.path;
        truncatedIndex = index;
        break;
      }
      report.push(line);
      emitted += 1;
    }
    report.push('```');
    report.push('');
  }

  if (truncatedAt) {
    // The truncated file is partial, not absent, so it is counted separately from the files
    // after it. Lumping the two together reported "all N files were not emitted" when
    // truncation landed in the first file, which is both wrong and alarming.
    const untouched = reviewable.length - truncatedIndex - 1;
    report.push(
      `> **Truncated at ${args.maxLines} diff lines.** \`${truncatedAt}\` is partial, and the ` +
        `${untouched} in-scope file(s) after it were not emitted at all ` +
        `(${reviewable.length} in scope). Re-run with a higher \`--max-lines\`, or review the ` +
        'remainder in a second pass so the gap is deliberate rather than silent.',
    );
  }

  process.stdout.write(`${report.join('\n')}\n`);
}

try {
  main();
} catch (error) {
  process.stderr.write(`[pr-review-diff] ${error.message}\n`);
  process.exit(1);
}
